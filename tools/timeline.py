#!/usr/bin/env python3
"""Write src/timeline.js from film/film.json: the reel has no narrator, so the script's own
event times are the timeline (picture and sound both read them).
usage: python3 tools/timeline.py film/film.json"""
import json, os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
spec = json.load(open(sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, 'film/film.json')))
out = os.path.join(ROOT, 'src', 'timeline.js')
with open(out, 'w') as f:
    f.write('// Generated by tools/timeline.py from film/film.json -- do not edit by hand.\n')
    f.write(f"export const DURATION = {spec['duration']};\n")
    f.write(f"export const EV = {json.dumps(spec['events'])};\n")
    f.write(f"export const CHAPTERS = {json.dumps(spec['chapters'], ensure_ascii=False)};\n")
    f.write(f"export const CARDS = {json.dumps(spec['cards'], ensure_ascii=False)};\n")
    f.write(f"export const BRAND = {json.dumps(spec['brand'], ensure_ascii=False)};\n")
    f.write('export const CUES = [];\n')
print('wrote', out)
